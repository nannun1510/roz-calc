"""Generate src/app/jobs/roz/roz-data.generated.ts from the ROZ client extraction.
Attack skills: ratio/hits/element/type parsed from the English skill descriptions,
timings from SkillDelayList (ms)."""
import json, re
s = json.load(open('tools/roz/roz-skills.json'))
t = json.load(open('tools/roz/roz-skill-trees.json'))
dl = json.load(open('tools/roz/roz-skilldelay.json'))['SKILL_DELAY_LIST']
JOBS = {'JT_SWORDMAN': 'Swordman', 'JT_MAGICIAN': 'Mage', 'JT_ARCHER': 'Archer', 'JT_ACOLYTE': 'Acolyte', 'JT_MERCHANT': 'Merchant', 'JT_THIEF': 'Thief',
        'JT_KNIGHT': 'Knight', 'JT_CRUSADER': 'Crusader', 'JT_WIZARD': 'Wizard', 'JT_SAGE': 'Sage', 'JT_HUNTER': 'Hunter', 'JT_BARD': 'Bard', 'JT_DANCER': 'Dancer',
        'JT_PRIEST': 'Priest', 'JT_MONK': 'Monk', 'JT_BLACKSMITH': 'Blacksmith', 'JT_ALCHEMIST': 'Alchemist', 'JT_ASSASSIN': 'Assassin', 'JT_ROGUE': 'Rogue', 'JT_NOVICE': 'Novice'}
ELEM = ['Neutral', 'Water', 'Earth', 'Fire', 'Wind', 'Poison', 'Holy', 'Dark', 'Shadow', 'Ghost', 'Undead']
def elem(text):
    m = re.search(r'\b(' + '|'.join(ELEM) + r')(?:-Property)? (?:Magical|Magic|physical|Physical)? ?[Dd]amage', text) or re.search(r'\b(' + '|'.join(ELEM) + r')-Property', text)
    if not m: return None
    e = m.group(1); return 'Dark' if e == 'Shadow' else e
trees, atk, skipped = {}, [], []
seen = set()
for jt, cls in JOBS.items():
    names = []
    for x in t[jt]['skills']:
        sk = s[str(x['id'])]
        if not sk['name']: continue
        names.append({'name': sk['name'], 'id': sk['id'], 'maxLv': sk['maxLv']})
        if sk['id'] in seen: continue
        seen.add(sk['id'])
        desc = ' '.join(sk['description'])
        mtype = re.search(r'Type : ([^|]+?)(?: Target|$| \|)', ' | '.join(sk['description']))
        typ = (mtype.group(1).strip() if mtype else '')
        lv = sk['levels']; maxLv = sk['maxLv'] or 1
        ratio, hits = [], []
        if not typ or typ in ('Support',):
            if re.search(r'Magical Damage', desc): typ = 'Magic'
            elif re.search(r'Ranged Physical|distant|Throws|Fires', desc): typ = 'Ranged Physical'
            elif re.search(r'Melee Physical|Strikes|Swings|around self|triple-hit|Basic attacks have', desc): typ = 'Melee Physical'
        if typ == 'Special (Magic)' and not re.search(r'ATK, MATK', ' '.join(e.get('text','') for e in lv.values())): typ = 'Magic'
        isMatk = 'Magic' in typ
        for L in range(1, maxLv + 1):
            e = lv.get(str(L), {}); txt = e.get('text', '')
            r = e.get('matkPercent' if isMatk else 'atkPercent') or e.get('atkPercent') or e.get('matkPercent')
            if r is None:
                m = re.search(r'(?:MATK|ATK) (\d+)%|(\d+)% of (?:MATK|ATK)', desc)
                r = int(m.group(1) or m.group(2)) if m else None
            h = e.get('hits')
            mh = re.search(r'%\s*[x×]\s?(\d+)', txt)
            if mh: h = int(mh.group(1))
            if h is None:
                mh = re.search(r'(?:Number of Hits|Hits|Meteors)[: ]+(\d+)', txt)
                if mh: h = int(mh.group(1))
            ratio.append(r); hits.append(h)
        dmg_type = ('magic' if isMatk else 'melee' if 'Melee' in typ else 'ranged' if 'Ranged' in typ else None)
        if 'Special' in typ or dmg_type is None or all(r is None for r in ratio) or 'ATK, MATK' in ' '.join(e.get('text','') for e in lv.values()):
            if re.search(r'[Dd]amage', desc): skipped.append((cls, sk['name'], typ))
            continue
        if any(r is None for r in ratio): ratio = [r if r is not None else next(x for x in ratio if x is not None) for r in ratio]
        if all(h is None for h in hits): hits = None
        else: hits = [h or 1 for h in hits]
        d = dl.get(str(sk['id']), {})
        def arr(key):
            v = d.get(key)
            if v is None: return [0] * maxLv
            if isinstance(v, (int, float)): return [v] * maxLv
            return (list(v) + [v[-1]] * maxLv)[:maxLv]
        extra = None
        m = re.search(r'\+ \((STR|AGI|VIT|INT|DEX|LUK) x\d+\)%', ' '.join(e.get('text','') for e in lv.values()))
        if m: extra = {'statPctPerLv': m.group(1).lower()}
        atk.append({'extra': extra, 'name': sk['name'], 'id': sk['id'], 'aegis': sk['aegisName'], 'maxLv': maxLv, 'type': dmg_type, 'element': elem(desc) if isMatk or re.search(r'-Property', desc) else None,
                    'ratio': ratio, 'hits': hits, 'fct': arr('SkillCastFixedDelay'), 'vct': arr('SkillCastStatDelay'), 'acd': arr('SkillGlobalPostDelay'), 'cd': arr('SkillSinglePostDelay'),
                    'timingKnown': bool(d)})
    trees[cls] = names
desc_by_name = {}
for v in s.values():
    if v['name']:
        desc_by_name[v['name']] = {'id': v['id'], 'label': v['name'], 'description': '\n'.join([v['name']] + v['description'])}
out = '/* eslint-disable */\n// GENERATED by tools/roz/gen-skills.py from the ROZ Global client (skilldescript_enus.lub,\n// skilltreeview.lub, skilldelaylist.lub). Do not edit by hand.\n'
out += 'export interface RozAtkSpec { name: string; id: number; aegis: string; maxLv: number; type: \'magic\' | \'melee\' | \'ranged\'; element: string | null; ratio: number[]; hits: number[] | null; fct: number[]; vct: number[]; acd: number[]; cd: number[]; timingKnown: boolean; extra: { statPctPerLv: string } | null; }\n'
out += 'export const ROZ_ATK_SKILLS: RozAtkSpec[] = ' + json.dumps(atk, ensure_ascii=False) + ';\n'
out += 'export const ROZ_SKILL_TREE: Record<string, { name: string; id: number; maxLv: number }[]> = ' + json.dumps(trees, ensure_ascii=False) + ';\n'
open('src/app/jobs/roz/roz-data.generated.ts', 'w').write(out)
json.dump(desc_by_name, open('tools/roz/roz-skill-meta.json', 'w'), ensure_ascii=False)
json.dump(skipped, open('tools/roz/roz-skills-not-modelled.json', 'w'), ensure_ascii=False, indent=0)
print('atk', len(atk)); print('skipped', len(skipped), skipped)
for a in atk[:0]: print(f"{a['name']:24} {a['type']:6} {str(a['element']):7} ratio {a['ratio'][0]}..{a['ratio'][-1]} hits {a['hits'] and (a['hits'][0], a['hits'][-1])} cd {a['cd'][-1]} {'' if a['timingKnown'] else 'NO-TIMING'}")
