"""ROZ consumables (run after convert-items-en.py / gen-enchants.py; appends to item.json).
itemTypeId 3 (Consumable). itemSubTypeId: 0 = buff item (Consumables list), 1 = stat food, 2 = ASPD potion.
Also writes src/app/constants/roz-consumables.ts (stat food list per stat, ASPD potions)."""
import json, re, collections
src = open('tools/roz/convert-items-en.py').read()
ns = {}; exec(compile(src[:src.index('META = re.compile(')], 'c', 'exec'), ns)
S, TH, clean, parse_line = ns['S'], ns['TH'], ns['clean'], ns['parse_line']
D = 'src/assets/demo/data/item.json'
items = json.load(open(D))

def desc(k):
    en = '\n'.join(S[k].get('identifiedDescriptionName') or [])
    th = '\n'.join((TH.get(k) or {}).get('identifiedDescriptionName') or [])
    return en + ('\n^0000ff──────── ภาษาไทย ────────^000000\n' + th if th else '')

def rec(k, sub, script):
    n = S[k]['identifiedDisplayName']
    return {'id': int(k), 'aegisName': f'ROZ_{k}', 'name': n, 'unidName': n, 'resName': '', 'description': desc(k), 'slots': 0,
            'itemTypeId': 3, 'itemSubTypeId': sub, 'itemLevel': None, 'attack': None, 'defense': None, 'weight': 0,
            'requiredLevel': None, 'location': None, 'compositionPos': None, 'usableClass': ['all'], 'script': script}

def script_of(k):
    sc = collections.defaultdict(list)
    for l in S[k].get('identifiedDescriptionName') or []:
        l = clean(l)
        l = re.sub(r'^(?:For \d+ minutes?|Grants)[,:]?\s*', '', l, flags=re.I)
        l = re.sub(r'\s*for \d+ (?:minutes?|hours?|hour)\.?$', '', l, flags=re.I)
        l = l.replace('All State', 'All Stats').replace('all stats', 'All Stats').replace('ATK/MATK', 'ATK/MATK').replace('HIT/FLEE', 'HIT/FLEE')
        l = re.sub(r'^(?:Recovers .*)$', '', l)
        if not re.search(r'[+-]\s*\d', l): continue
        r = parse_line(l)
        if r is None:
            r = []
            for part in re.split(r',\s*|\.\s+', l):
                part = re.sub(r'^and\s+', '', part.strip().rstrip('.'))
                rr = parse_line(part) if part else []
                if rr: r += rr
        for kk, v in r: sc[kk].append(str(v))
    return dict(sc)

out = {}
# 1) buff consumables (one per name; skip boxes)
BUFF_NAMES = ['Premium Course Meal', 'Blessing of Yggdrasil', 'Cold Watermelon Juice', '[Event] Muscle Activation Potion',
              '[Event] Passion Guild Ticket', '[Event] Calm Guild Ticket'] + [f'Mixed Dish Lv.{i}' for i in range(5, 11)]
seen = set()
for k, v in sorted(S.items(), key=lambda kv: int(kv[0])):
    n = v.get('identifiedDisplayName', '')
    if n in BUFF_NAMES and n not in seen:
        sc = script_of(k)
        if sc: out[k] = rec(k, 0, sc); seen.add(n)
# 2) stat foods: cooked foods that give exactly one stat (ids 11500-12200)
foods = collections.defaultdict(dict)
for k, v in S.items():
    if not (11500 <= int(k) <= 12200): continue
    d = ' '.join(v.get('identifiedDescriptionName') or [])
    m = re.findall(r'\b(STR|AGI|VIT|INT|DEX|LUK) \+(\d+)\b', d)
    if len(m) == 1 and 'Stone' not in v['identifiedDisplayName']:
        st, val = m[0][0], int(m[0][1])
        if val not in foods[st] or int(k) < int(foods[st][val]):
            foods[st][val] = k
for st, d in foods.items():
    for val, k in d.items(): out[k] = rec(k, 1, {st.lower(): [str(val)]})
# 3) ASPD potions (fixed ASPD bonus handled by the app)
for k in ['645', '656', '657', '107045']:
    if k in S: out[k] = rec(k, 2, {})
items.update(out)
json.dump(items, open(D, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

food_ts = ',\n'.join('  [' + ', '.join(f"{{ label: '{st.capitalize()} {val}', value: {k} }}" for val, k in sorted(foods[st].items())) + ']'
                     for st in ['STR', 'AGI', 'VIT', 'INT', 'DEX', 'LUK'])
open('src/app/constants/roz-consumables.ts', 'w').write(f"""// GENERATED by tools/roz/gen-consumables.py from the ROZ item table.
import {{ DropdownModel }} from '../models/dropdown.model';

/** ROZ cooked stat foods (one per stat, +1..+10). */
export const RozFoodStatList: DropdownModel[][] = [
{food_ts}
];
""")
print('buff items', [(o['name'], o['script']) for o in out.values() if o['itemSubTypeId'] == 0])
print('foods', {st: sorted(d) for st, d in foods.items()})
